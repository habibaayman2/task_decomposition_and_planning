"""
Thin SQLite access layer for the IronBridge Procurement MCP server.

Every tool handler in server.py goes through here rather than writing
ad-hoc SQL inline. Business-rule validation lives in validation.py, not
here — this module only knows how to read/write rows.

Designed to import cleanly in any context: a plain script, a package
under mcp_server/, or pasted/exec'd in a Jupyter notebook — on any
Python 3.7+ interpreter.
"""

import hashlib
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Optional, List, Dict, Any


def _find_db_path() -> str:
    """
    Locate procurement.db without assuming a fixed folder depth or name.

    Priority:
      1. IRONBRIDGE_DB_PATH env var, if set — always wins.
      2. An existing db/procurement.db found by checking, in order:
         - next to this file            (this file's dir)/db/procurement.db
         - one level up from this file  (..)/db/procurement.db
         - the current working directory: cwd/db/procurement.db
         - one level up from cwd:       cwd/../db/procurement.db
      3. If none of those already exist, fall back to cwd/db/procurement.db
         so a fresh `build_db.py` run has a predictable place to create it.
    """
    env_path = os.environ.get("IRONBRIDGE_DB_PATH")
    if env_path:
        return env_path

    try:
        this_dir = Path(__file__).resolve().parent
    except NameError:
        this_dir = None  # __file__ not defined (REPL/notebook exec context)

    candidates = []
    if this_dir is not None:
        candidates.append(this_dir / "db" / "procurement.db")
        candidates.append(this_dir.parent / "db" / "procurement.db")
    cwd = Path.cwd()
    candidates.append(cwd / "db" / "procurement.db")
    candidates.append(cwd.parent / "db" / "procurement.db")

    for candidate in candidates:
        if candidate.exists():
            return str(candidate)

    # Nothing found yet — default to cwd/db/procurement.db so a fresh
    # `build_db.py` run has a predictable place to create it.
    return str(cwd / "db" / "procurement.db")


DB_PATH = _find_db_path()

# sqlite3.connect() will create the .db FILE if missing, but NOT missing
# parent directories — that's the other common cause of
# "unable to open database file". Make sure the folder exists.
Path(DB_PATH).resolve().parent.mkdir(parents=True, exist_ok=True)


@contextmanager
def get_conn():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def hash_pin(pin: str) -> str:
    return hashlib.sha256(pin.encode()).hexdigest()


