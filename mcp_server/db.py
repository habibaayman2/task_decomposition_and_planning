def get_employee(employee_id: int) -> Optional[Dict[str, Any]]:
    with get_conn() as conn:
        row = conn.execute("SELECT * FROM Employees WHERE EmployeeID = ?", (employee_id,)).fetchone()
        return dict(row) if row else None


