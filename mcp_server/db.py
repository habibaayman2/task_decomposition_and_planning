def project_requests_in_range(project_id: int, start_date: str, end_date: str) -> List[Dict[str, Any]]:
    with get_conn() as conn:
        rows = conn.execute(
            """
            SELECT pr.*, m.MaterialName, e.Name AS RequestedBy
            FROM PurchaseRequests pr
            JOIN MaterialInventory m ON m.MaterialID = pr.MaterialID
            JOIN Employees e ON e.EmployeeID = pr.EmployeeID
            WHERE pr.ProjectID = ? AND date(pr.RequestDate) BETWEEN date(?) AND date(?)
            ORDER BY pr.RequestDate
            """,
            (project_id, start_date, end_date),
        ).fetchall()
        return [dict(r) for r in rows]


