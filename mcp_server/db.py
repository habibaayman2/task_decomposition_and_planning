def find_materials(category: Optional[str], name_contains: Optional[str]) -> List[Dict[str, Any]]:
    with get_conn() as conn:
        query = "SELECT * FROM MaterialInventory WHERE 1=1"
        params = []
        if category:
            query += " AND Category = ?"
            params.append(category)
        if name_contains:
            query += " AND MaterialName LIKE ?"
            params.append(f"%{name_contains}%")
        rows = conn.execute(query, params).fetchall()
        return [dict(r) for r in rows]


