def create_purchase_request(project_id, employee_id, material_id, quantity):
    with get_conn() as conn:
        material = conn.execute(
            "SELECT UnitPrice FROM MaterialInventory WHERE MaterialID = ?", (material_id,)
        ).fetchone()
        if material is None:
            raise ValueError(f"Unknown MaterialID {material_id}")
        estimated_cost = material["UnitPrice"] * quantity
        cur = conn.execute(
            """
            INSERT INTO PurchaseRequests
                (ProjectID, EmployeeID, MaterialID, Quantity, EstimatedCost, ApprovalLevel, Status)
            VALUES (?, ?, ?, ?, ?, 1, 'Pending')
            """,
            (project_id, employee_id, material_id, quantity, estimated_cost),
        )
        request_id = cur.lastrowid
        log_action(conn, employee_id, "create_purchase_request", request_id, f"qty={quantity}, est_cost={estimated_cost}")
        return request_id, estimated_cost


def approve_purchase_request(request_id: int, approver_id: int):
    with get_conn() as conn:
        req = conn.execute(
            "SELECT ProjectID, EstimatedCost FROM PurchaseRequests WHERE RequestID = ?",
            (request_id,),
        ).fetchone()
        if req is None:
            raise ValueError(f"Unknown RequestID {request_id}")
        conn.execute("UPDATE PurchaseRequests SET Status = 'Approved' WHERE RequestID = ?", (request_id,))
        # Approval is the point budget actually gets committed (an
        # escalated request never reaches this path — see
        # validate_request_pending, which requires Status='Pending' — so
        # there's no double-counting between escalation and approval).
        # Without this, RemainingBudget never moves and
        # validation.validate_within_budget's "hard block" becomes a
        # no-op after the first approval: it keeps comparing new
        # requests against a remaining-budget figure that never shrinks.
        conn.execute(
            "UPDATE Projects SET RemainingBudget = RemainingBudget - ? WHERE ProjectID = ?",
            (req["EstimatedCost"], req["ProjectID"]),
        )
        log_action(conn, approver_id, "approve_purchase_request", request_id, "approved")


def escalate_purchase_request(request_id: int, reason: str, actor_id: int):
    with get_conn() as conn:
        conn.execute(
            "UPDATE PurchaseRequests SET Status = 'Escalated', ApprovalLevel = ApprovalLevel + 1 WHERE RequestID = ?",
            (request_id,),
        )
        log_action(conn, actor_id, "escalate_purchase_request", request_id, reason)


def reserve_material(request_id: int, material_id: int, quantity: float, actor_id: int):
    with get_conn() as conn:
        conn.execute(
            "UPDATE MaterialInventory SET QuantityAvailable = QuantityAvailable - ?, LastUpdated = datetime('now') WHERE MaterialID = ?",
            (quantity, material_id),
        )
        conn.execute("UPDATE PurchaseRequests SET Status = 'Reserved' WHERE RequestID = ?", (request_id,))
        log_action(conn, actor_id, "reserve_material", request_id, f"qty={quantity}")


def log_action(conn, actor_id, action, target_id, detail):
    conn.execute(
        "INSERT INTO AuditLog (ActorID, Action, TargetID, Detail) VALUES (?, ?, ?, ?)",
        (actor_id, action, target_id, detail),
    )
